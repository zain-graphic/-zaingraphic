function openPage(pageId, fromHistory = false) {
  closeServices();

  if (pageClosing) {
    fullPage.classList.remove('closing');
    pageClosing = false;
  }

  if (fullPage.classList.contains('active') && currentPage && currentPage !== pageId && !fromHistory) {
    pageHistory.push(currentPage);
  }

  if (!fromHistory && (!fullPage.classList.contains('active') || currentPage !== pageId)) {
    history.pushState({ zainGraphicPage: pageId }, '', window.location.href);
  }

  const contents = document.querySelectorAll('.page-content');
  contents.forEach(function (content) {
    content.style.display = 'none';
    content.classList.remove('page-enter-refresh');
  });

  const selectedContent = document.getElementById('page-' + pageId);
  if (!selectedContent) {
    console.error('Page not found:', pageId);
    return;
  }

  selectedContent.style.display = 'block';
  selectedContent.style.animation = 'none';
  void selectedContent.offsetWidth;
  selectedContent.style.animation = '';

  const pageTitle = document.getElementById('pageTitle');
  pageTitle.textContent = titlesMap[pageId] || 'القسم';

  currentPage = pageId;
  updateBackButton();

  fullPage.classList.add('active');
  fullPage.classList.remove('closing');
  document.body.classList.add('page-open');

  requestAnimationFrame(function () {
    fullPage.scrollTo({ top: 0, behavior: 'auto' });
  });
}

function goBackPage() {
  if (pageHistory.length === 0) {
    if (fullPage.classList.contains('active')) {
      history.back();
    }
    return;
  }
  history.back();
}

function closePage(fromBrowserBack = false) {
  if (!fullPage.classList.contains('active') || pageClosing) {
    return;
  }

  if (!fromBrowserBack) {
    const stepsBack = pageHistory.length + 1;
    pageHistory = [];
    if (history.state && history.state.zainGraphicPage) {
      browserNavigation = true;
      history.go(-stepsBack);
      return;
    }
  }

  pageClosing = true;
  fullPage.classList.remove('active');
  fullPage.classList.add('closing');
  document.body.classList.remove('page-open');

  fullPage.querySelectorAll('video').forEach(function (video) {
    video.pause();
    video.currentTime = 0;
    video.classList.add('is-blurred');
  });

  fullPage.querySelectorAll('.glass-play-btn').forEach(function (button) {
    button.classList.remove('is-hidden');
  });

  const finishClose = function () {
    fullPage.removeEventListener('animationend', finishClose);
    fullPage.classList.remove('closing');
    currentPage = null;
    pageHistory = [];
    pageClosing = false;
    updateBackButton();

    if (teaserVideo) {
      teaserVideo.muted = true;
      teaserVideo.play().catch(function () {});
    }
  };

  fullPage.addEventListener('animationend', finishClose);
  setTimeout(finishClose, 450);
}

function goHome() {
  closeServices();
  if (fullPage.classList.contains('active')) {
    closePage();
    return;
  }
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

let servicesClosing = false;

function toggleServices() {
  if (servicesMenu.classList.contains('show') || servicesMenu.classList.contains('closing')) {
    closeServices();
    return;
  }
  servicesClosing = false;
  servicesMenu.classList.remove('closing');
  servicesMenu.classList.add('show');
  servicesButton.setAttribute('aria-expanded', 'true');
}

function closeServices() {
  if (servicesClosing || (!servicesMenu.classList.contains('show') && !servicesMenu.classList.contains('closing'))) {
    servicesButton.setAttribute('aria-expanded', 'false');
    return;
  }
  servicesClosing = true;
  servicesMenu.classList.remove('show');
  servicesMenu.classList.add('closing');
  servicesButton.setAttribute('aria-expanded', 'false');

  const finishServices = function () {
    servicesMenu.removeEventListener('animationend', finishServices);
    servicesMenu.classList.remove('closing');
    servicesClosing = false;
  };

  servicesMenu.addEventListener('animationend', finishServices);
  setTimeout(finishServices, 350);
}

