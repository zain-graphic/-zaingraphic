document.querySelector(
'.teaser-video'
);

if(teaserVideo){

teaserVideo.muted=true;

teaserVideo.autoplay=true;

teaserVideo.loop=true;

teaserVideo.playsInline=true;

teaserVideo.play().catch(
function(){}
);

}

document.addEventListener(
'click',
function(){

if(
teaserVideo &&
teaserVideo.paused
){

teaserVideo.muted=true;

teaserVideo.play().catch(
function(){}
);

}

},
{
once:false,
passive:true
}
);
