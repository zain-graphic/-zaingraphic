function createWorkCard(item) {
  const card = document.createElement('div');
  card.className = 'work-card-glass';

  const media = document.createElement('div');
  media.className = 'work-img-wrapper';

  if (item.type === 'video') {
    const playButton = document.createElement('button');
    playButton.className = 'glass-play-btn';
    playButton.setAttribute('aria-label', 'تشغيل الفيديو');

    const video = document.createElement('video');
    video.className = 'work-video is-blurred';
    video.controls = true;
    video.playsInline = true;
    video.preload = 'metadata';

    const source = document.createElement('source');
    source.src = item.src;
    source.type = 'video/mp4';

    video.appendChild(source);
    media.appendChild(playButton);
    media.appendChild(video);

    setupVideo(video, playButton);
  } else {
    const image = document.createElement('img');
    image.src = item.src;
    image.alt = item.title;
    image.loading = 'lazy';
    image.decoding = 'async';
    image.onerror = function () {
      imageFallback(this);
    };

    media.appendChild(image);
  }

  const info = document.createElement('div');
  info.className = 'work-info-box';

  const title = document.createElement('span');
  title.className = 'work-title';
  title.textContent = item.title;

  const desc = document.createElement('p');
  desc.className = 'work-desc';
  desc.textContent = item.desc;

  const tag = document.createElement('span');
  tag.className = 'work-tag';
  tag.textContent = item.tag;

  info.appendChild(title);
  info.appendChild(desc);
  info.appendChild(tag);

  card.appendChild(media);
  card.appendChild(info);

  return card;
}

